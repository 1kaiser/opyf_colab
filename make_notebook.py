"""
make_notebook.py — generate pipeline_notebook.ipynb from pipeline.py stages.

Usage:
    conda run -n num_gpu python3 make_notebook.py
    # or dry-run (just write the .ipynb, don't execute):
    conda run -n num_gpu python3 make_notebook.py --no-execute

The notebook mirrors pipeline.py stage-by-stage. Each stage becomes:
    - a Markdown cell with title + description
    - a Code cell

Papermill parameters are in the first code cell tagged "parameters".
"""

