def md(source: str) -> nbformat.NotebookNode:
    return new_markdown_cell(source)


def code(source: str, tags: list[str] | None = None) -> nbformat.NotebookNode:
    c = new_code_cell(source)
    if tags:
        c["metadata"]["tags"] = tags
    return c


