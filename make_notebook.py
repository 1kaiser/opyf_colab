def build_notebook() -> nbformat.NotebookNode:
    nb = new_notebook()
    nb["metadata"] = {
        "kernelspec": {
            "display_name": "num_gpu",
            "language": "python",
            "name": "num_gpu",
        },
        "language_info": {
            "name": "python",
            "version": "3.11",
        },
    }
    nb["cells"] = CELLS
    return nb


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="pipeline_notebook.ipynb")
    p.add_argument("--no-execute", action="store_true",
                   help="Write notebook without executing it")
    args = p.parse_args()

    nb = build_notebook()
    with open(args.out, "w") as f:
        nbformat.write(nb, f)
    print(f"Wrote {args.out}  ({len(nb['cells'])} cells)")

    if not args.no_execute:
        print("Validating notebook structure …")
        nbformat.validate(nb)
        print("Notebook is valid. Run with Papermill:")
        print(f"  conda run -n num_gpu papermill {args.out} {args.out} "
              f"-p SKIP_DEPTH True -p SKIP_ALIGN True")


if __name__ == "__main__":
    main()
